# ================================================================
# Main dispatcher
# ================================================================
main() {
  local subcmd="${1:-help}"
  shift || true

  case "$subcmd" in
    install)         cmd_install "$@" ;;
    remove)          cmd_remove "$@" ;;
    update)          cmd_update "$@" ;;
    list)            cmd_list "$@" ;;
    docs)            cmd_docs "$@" ;;
    check-updates)   cmd_check_updates "$@" ;;
    audit)           cmd_audit "$@" ;;
    new)             cmd_new "$@" ;;
    publish)         cmd_publish "$@" ;;
    generate-loader) require_plugins_dir; ensure_registry_valid; generate_loader ;;
    help|--help|-h)  cmd_help ;;
    *) echo "  [plugin] Unknown subcommand: ${subcmd}" >&2; cmd_help; exit 1 ;;
  esac
}

main "$@"
