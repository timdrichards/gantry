    new <name> [--description <desc>] [--author <author>] [--version <ver>]
        Scaffold a new plugin in .plugins/<name>/ with full directory
        structure, starter files, and an initial git commit.
        Prompts interactively for any fields not supplied as flags.

    publish <name> [--public|--private] [--org <org>]
        Push a locally developed plugin to GitHub.
        Creates a new GitHub repo if no remote is configured.
        Updates plugin.json with the repository URL after publishing.
        Requires 'gh auth login' on the host (or GH_TOKEN env var).

    generate-loader
        Regenerate .plugins/.loader.sh from the registry.
        Run this if plugin commands are missing after a rebuild.

    help
        Show this message.

  PLUGIN STRUCTURE
    Each plugin is a git repo with:
      plugin.json       manifest (name, version, description, dependencies, env)
      bin/              executables added to PATH
      lib/shell.sh      aliases/functions sourced at login
      docs/README.md    documentation

  SECURITY
    • Only install plugins from trusted HTTPS sources.
    • Review lib/shell.sh with: plugin audit <name>
    • Plugins run as the 'vscode' user — no root escalation.
    • Plugin names are restricted to [a-zA-Z0-9_-].

HELP
